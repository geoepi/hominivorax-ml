testthat::test_that("P7E rolling-origin aggregation is complete and leakage-safe", {
  root <- testthat::test_path("..", "..", "analysis", "p7e_rolling_forecasts")
  results <- file.path(root, "results")
  testthat::expect_true(file.exists(file.path(results, "validation_results.json")))
  validation <- jsonlite::fromJSON(file.path(results, "validation_results.json"), simplifyVector = TRUE)
  testthat::expect_identical(validation$status, "P7E_VALIDATION_PASSED")
  occ <- utils::read.csv(file.path(results, "rolling_occurrence_forecasts.csv"), stringsAsFactors = FALSE)
  testthat::expect_equal(nrow(occ), 63L)
  testthat::expect_equal(sort(unique(occ$horizon)), 1:3)
  testthat::expect_equal(sort(unique(occ$issue_week)), sprintf("2026-W%02d", 16:36))
  testthat::expect_true(all(occ$target_week == sprintf("2026-W%02d", as.integer(sub(".*-W", "", occ$issue_week)) + occ$horizon)))
  testthat::expect_true(all(abs(occ$forecast_error - (occ$expected_positive_cells - occ$observed_positive_cells)) < 1e-10))
  contract <- jsonlite::fromJSON(file.path(results, "rendering_contract.json"), simplifyVector = TRUE)
  testthat::expect_identical(contract$uncertainty_status, "NOT_SUPPORTED_BY_CURRENT_CANONICAL_ARTIFACTS")
  testthat::expect_true(isTRUE(contract$no_uncertainty_ribbon))
  testthat::expect_false(isTRUE(contract$model_fitting))
})
